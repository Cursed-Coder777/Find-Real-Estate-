function svgToComponent(name, svg, propsDoc) {
  if (!svg) throw new Error("missing svg for " + name);
  let jsx = htmlToJsx(svg)
    .split("\n")
    .map((l) => "    " + l)
    .join("\n");
  // hoist the root svg attrs so callers can size it
  jsx = jsx
    .replace(/^ {4}<svg /, "    <svg {...props} ")
    // The origin leaves GSAP's stroke-draw endpoints inline (a zero-length dash,
    // i.e. an invisible stroke). Drop them so the wordmark renders fully drawn.
    .replace(/\s*strokeDashoffset: "[^"]*",?/g, "")
    .replace(/\s*strokeDasharray: "[^"]*",?/g, "")
    .replace(/style=\{\{\s*\}\}/g, "");
  return `export function ${name}(props: SVGProps<SVGSVGElement>) {\n  return (\n${jsx}\n  );\n}`;
}

