function firstSvg(html) {
  const i = html.indexOf("<svg");
  if (i === -1) return null;
  // find matching close
  let depth = 0;
  const re = /<(\/?)svg\b[^>]*?(\/?)>/g;
  re.lastIndex = i;
  let m;
  while ((m = re.exec(html))) {
    if (m[1] === "/") {
      depth--;
      if (depth === 0) return html.slice(i, m.index + m[0].length);
    } else if (!m[2]) {
      depth++;
    }
  }
  return null;
}

const header = fs.readFileSync(path.join(RES, "chrome/header.html"), "utf8");
